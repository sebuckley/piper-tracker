export const searchEmojis = term => {
  const t = (term || "").trim().toLowerCase();
  if (!t) return REWARD_EMOJIS;
  return REWARD_EMOJIS.filter(e => e.keywords.includes(t) || e.keywords.split(" ").some(w => w.startsWith(t)));
};
