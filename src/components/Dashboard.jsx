import { useState } from "react";
import { useAppStore } from "../store/useAppStore";
import ActivityCard from "./activity/ActivityComponent";
import RewardCard from "./rewards/RewardCard";

export default function Dashboard() {
  // Unified store selectors
  const behaviour = useAppStore(s => s.behaviourLogs);
  const achievements = useAppStore(s => s.achievements);
  const rewardLogs = useAppStore(s => s.rewardLogs);
  const starBalance = useAppStore(s => s.starBalance);
  const sportsFeedback = useAppStore(s => s.sportsFeedback);
  const sportsClasses = useAppStore(s => s.sportsClasses);



  const activeChild = useAppStore(s => s.activeChild);
  const children = useAppStore(s => s.children);

  const child = children.find(c => c.id === activeChild);
  const isEditor = useAppStore(s => s.isEditor());
  const isOwner = useAppStore(s => s.isOwner());

  // ⭐ FILTER STATES
  const [filter, setFilter] = useState("last7");
  const [activityFilter, setActivityFilter] = useState("all");

  // ⭐ DATE FILTER LOGIC
  const now = new Date();
  const todayStart = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  const monthStart = new Date(now.getFullYear(), now.getMonth(), 1);
  const yearStart = new Date(now.getFullYear(), 0, 1);
  const sevenDaysAgo = new Date(now.getFullYear(), now.getMonth(), now.getDate() - 7);

  function passesFilter(dateString) {
    const d = new Date(dateString);

    if (isNaN(d.getTime())) return false;

    switch (filter) {
      case "today":
        return d >= todayStart;
      case "last7":
        return d >= sevenDaysAgo;
      case "month":
        return d >= monthStart;
      case "year":
        return d >= yearStart;
      case "all":
        return true;
      default:
        return true;
    }
  }

  function normalizeDate(dateString) {
    // If date is YYYY-MM-DD, convert to local midnight
    if (/^\d{4}-\d{2}-\d{2}$/.test(dateString)) {
      const [y, m, d] = dateString.split("-");
      return new Date(Number(y), Number(m) - 1, Number(d));
    }

    // Otherwise parse normally
    return new Date(dateString);
  }


  // ⭐ FILTERED DATA
  const filteredBehaviour = behaviour.filter(b => passesFilter(b.date));
  const filteredAchievements = achievements.filter(a => passesFilter(a.date));
  const filteredRewards = rewardLogs.filter(r => passesFilter(r.date));
  const filteredFeedback = sportsFeedback.filter(f => passesFilter(f.date));

  // ⭐ CALCULATIONS
  const behaviourStars = filteredBehaviour.reduce((sum, b) => sum + b.stars, 0);
  const achievementStars = filteredAchievements.reduce((sum, a) => sum + a.stars, 0);
  const redeemedStars = filteredRewards.reduce((sum, r) => sum + (r.cost ?? r.stars ?? 0), 0);
  const removedStars = filteredBehaviour
    .filter(b => b.stars < 0)
    .reduce((sum, b) => sum + Math.abs(b.stars), 0);

  const starsThisPeriod =
    behaviourStars +
    achievementStars -
    redeemedStars;

  // ⭐ Unified activity feed
  // Behaviour logs generated by session feedback are replaced by the feedback entries below
  let activities = [
    ...filteredBehaviour.filter(b => !String(b.category || "").endsWith(" feedback")).map(b => ({
      type: "Behaviour",
      title: b.category,
      description: b.description,
      stars: b.stars,
      date: b.date,
      addedBy: b.addedBy
    })),
    ...filteredAchievements.map(a => {

      return {
        type: "Achievement",
        title: a.title,
        description: a.description,
        stars: a.stars,
        emoji: a.emoji,
        date: a.date,
        addedBy: a.addedBy
      };
    }),
    ...filteredFeedback.map(f => {
      const sport = sportsClasses.find(s => s.templateId === f.sportId || s.id === f.sportId);
      const sportName = f.sportName || sport?.name || "Sport";
      const hasStars = (f.starsAwarded || 0) > 0;
      const text = f.mode === "simple"
        ? (f.notes || f.overall?.summary || "")
        : `Score ${f.score ?? "N/A"}/10${f.overall?.summary ? ` — ${f.overall.summary}` : ""}`;

      return {
        type: "Feedback",
        title: hasStars
          ? `${sportName} (${f.mode === "simple" ? "simple" : "detailed"})`
          : `${sportName} feedback received`,
        description: hasStars ? (text || "No feedback text") : "Session feedback received",
        stars: f.starsAwarded || 0,
        date: f.date,
        addedBy: f.addedBy,
        link: `/sports/${sport?.templateId ?? f.sportId}/history`
      };
    }),
...filteredRewards.map(r => {
  const cost = r.cost ?? r.stars ?? 0;

  let date = r.date;
  if (!date || isNaN(normalizeDate(date).getTime())) {
    date = new Date().toISOString().split("T")[0]; // store as YYYY-MM-DD
  }

  return {
    // Existing simplified activity fields
    type: "Reward Redeemed",
    title: r.rewardName || r.name || "Reward",
    description: `Redeemed for ${cost} stars`,
    stars: -cost,
    date,

    // ⭐ Full log fields preserved
    id: r.id,
    rewardId: r.rewardId,
    name: r.name,
    category: r.category,
    emoji: r.emoji,
    cost: r.cost,
    repeatable: r.repeatable,
    remainingStars: r.remainingStars,
    confirmedBy: r.confirmedBy,
    confirmedAt: r.confirmedAt,
    confirmedDeviceId: r.confirmedDeviceId
  };

})

  ];

  // ⭐ Apply sub-filter (FIXED)
  activities = activities.filter(a => {
    if (activityFilter === "all") return true;
    if (activityFilter === "behaviour") return a.type === "Behaviour";
    if (activityFilter === "achievement") return a.type === "Achievement";
    if (activityFilter === "feedback") return a.type === "Feedback";
    if (activityFilter === "removed") return a.type === "Behaviour" && a.stars < 0;
    if (activityFilter === "redeemed") return a.type === "Reward Redeemed";
    return true;
  });

  // Sort newest first
  activities.sort((a, b) => new Date(b.date) - new Date(a.date));

  return (
  <div className="container mt-4" style={{ maxWidth: "1200px" }}>
    
    {/* PAGE TITLE */}
    <h2 className="h3 mt-3 mb-4 text-center" style={{ color: "#b300ff", fontWeight: 700, letterSpacing: "0.5px" }}>
      {child?.preferredName || child?.firstName ||  "Child"}'s Dashboard
    </h2>

    {/* MAIN FILTER BUTTONS */}
    <div className="d-flex gap-3 flex-wrap justify-content-center mb-3">
      {[
        ["today", "Today"],
        ["last7", "Last 7 Days"],
        ["month", "This Month"],
        ["year", "This Year"],
        ["all", "All Time"]
      ].map(([key, label]) => (
        <button
          key={key}
          className="btn"
          style={{
            backgroundColor: filter === key ? "#b300ff" : "#ffffff",
            color: filter === key ? "white" : "#1f2a44",
            borderRadius: "10px",
            border: filter === key ? "2px solid #b300ff" : "1px solid #dcdcdc",
            fontWeight: "600",
            padding: "8px 16px"
          }}
          onClick={() => setFilter(key)}
        >
          {label}
        </button>
      ))}
    </div>

    {/* SUB FILTER BUTTONS */}
    <div className="d-flex gap-2 flex-wrap justify-content-center mb-4">
      {[
        ["all", "All"],
        ["behaviour", "Behaviour"],
        ["achievement", "Achievements"],
        ["feedback", "Feedback"],
        ["removed", "Removed"],
        ["redeemed", "Redeemed"]
      ].map(([key, label]) => (
        <button
          key={key}
          className="btn btn-sm"
          style={{
            backgroundColor: activityFilter === key ? "#b300ff" : "#ffffff",
            color: activityFilter === key ? "white" : "#1f2a44",
            borderRadius: "8px",
            border: activityFilter === key ? "2px solid #b300ff" : "1px solid #dcdcdc",
            fontWeight: "600",
            padding: "4px 10px",
            fontSize: "12px"
          }}
          onClick={() => setActivityFilter(key)}
        >
          {label}
        </button>
      ))}
    </div>

    {/* CURRENT STARS */}
    <div className="d-flex justify-content-center mb-4">
      <div
        className="p-3 text-center"
        style={{
          backgroundColor: "white",
          borderRadius: "16px",
          border: "1px solid #e6e6e6",
          minWidth: "220px",
          padding: "16px"
        }}
      >
        <h3 className="h6 mb-2" style={{ color: "#1f2a44", fontWeight: 700 }}>
          Current Stars
        </h3>
        <div style={{ fontSize: "32px", fontWeight: 800, color: "#b300ff" }}>
          {starBalance} ⭐
        </div>
      </div>
    </div>

    {/* STATS ROW */}
    <div className="d-flex justify-content-center gap-4 flex-wrap mb-4">
      {[
        ["Stars (" + filter + ")", starsThisPeriod, starsThisPeriod >= 0 ? "#b300ff" : "#cc0033"],
        ["Removed Stars", -removedStars, "#cc0033"],
        ["Redeemed", -redeemedStars, "#cc0033"]
      ].map(([label, value, colour], idx) => (
        <div
          key={idx}
          className="p-3 text-center"
          style={{
            backgroundColor: "white",
            borderRadius: "16px",
            border: "1px solid #e6e6e6",
            minWidth: "220px",
            padding: "16px"
          }}
        >
          <h3 className="h6 mb-2" style={{ color: "#1f2a44", fontWeight: 600 }}>
            {label}
          </h3>
          <div style={{ fontSize: "28px", fontWeight: 700, color: colour }}>
            {value} ⭐
          </div>
        </div>
      ))}
    </div>

    {/* LATEST ACTIVITIES */}
    <div className="mb-4">
      <h3 className="h4 mb-3" style={{ color: "#1f2a44", fontWeight: 600 }}>
        Latest Activities
      </h3>

      {activities.length === 0 && (
        <div
          className="text-muted"
          style={{
            backgroundColor: "white",
            borderRadius: "16px",
            border: "1px solid #e6e6e6",
            padding: "16px"
          }}
        >
          No activities logged for this period
        </div>
      )}

{activities.slice(0, 5).map((a, idx) => {


  const type = a.type;

  return (
    type !== "Reward Redeemed" ? (
    <ActivityCard
      key={idx}
      activity={a}
      canManage={isEditor || isOwner}
      onEdit={() => handleEditActivity(a)}
      onDelete={() => handleDeleteActivity(a)}
    />  )
    : (
    
      <RewardCard
        key={a.id}
        item={a}
        type="log"
        onRedeem={() => {}}
        onRequest={() => {}}
      />
    
    )
  );
})}

    </div>

  </div>
);
}
